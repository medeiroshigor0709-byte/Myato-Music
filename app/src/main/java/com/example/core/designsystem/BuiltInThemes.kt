    fun resolveThemeId(themeId: String?): String {
        if (themeId.isNullOrBlank()) return MyatoOriginal.id
        return legacyIdAliases[themeId] ?: themeId
    }

    fun findByIdOrAlias(themeId: String?): MyatoTheme? {
        val canonical = resolveThemeId(themeId)
        return all.firstOrNull { it.id == canonical }
